/**
 * Writes supabase/functions/_shared/markets.ts, the edge functions' copy of the market registry
 * (lib/markets.ts MARKET_CONFIG, lib/brand.ts BRANDS). The functions are deployed without the rest of
 * the repository, so they cannot import it; this file is what they read instead, and
 * tests/unit/markets-edge.test.ts fails while it differs from what this would write.
 *
 *   npm run markets:edge            write it
 *   npm run markets:edge -- --check exit 1 if it is not current
 *
 * scripts/functions/deploy.mjs runs it before every check and deploy.
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { BRANDS } from '../../lib/brand'
import { MARKET_CONFIG, MARKETS, type MarketConfig } from '../../lib/markets'

export const EDGE_MARKETS_PATH = 'supabase/functions/_shared/markets.ts'

const pick = <T>(f: (c: MarketConfig) => T | null): Record<string, T> =>
  Object.fromEntries(MARKETS.flatMap((m) => {
    const v = f(MARKET_CONFIG[m])
    return v === null ? [] : [[m, v]]
  }))

/** a value as this codebase writes it: single quotes, bare keys, one line */
const lit = (v: unknown): string => {
  if (typeof v === 'string') return `'${v.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`
  if (v && typeof v === 'object') return `{ ${Object.entries(v).map(([k, x]) => `${k}: ${lit(x)}`).join(', ')} }`
  return String(v)
}

/** The file's text, as this registry has it */
export function edgeMarkets(): string {
  return `// generated by \`npm run markets:edge\` (scripts/markets/edge.ts) from lib/markets.ts — do not edit.
// The market registry for the edge functions, which are deployed without lib/. Pure: no imports.

/** Each market's brand name (MarketConfig.brand, lib/brand.ts BRANDS): what a notice there calls the product, and the sender's name */
export const MARKET_BRAND_NAME: Readonly<Record<string, string>> = ${lit(pick((c) => BRANDS[c.brand].name))}

/** A market's own site, once it is open (MarketConfig.site): where its organisations' links lead in production */
export const MARKET_SITE_URL: Readonly<Record<string, string>> = ${lit(pick((c) => (c.site?.open ? c.site.url : null)))}

/** The language of an Auth mail asked for on a market's site by someone who named none (MarketConfig.authLang) */
export const MARKET_AUTH_LANG: Readonly<Record<string, 'en'>> = ${lit(pick((c) => c.authLang))}

/** A brand's own mail domain, used once Brevo reports it authenticated (MarketConfig.mailDomain) */
export const MARKET_MAIL_DOMAIN: Readonly<Record<string, string>> = ${lit(pick((c) => c.mailDomain))}

/** Each market's time zone, the clock its notices' dates are on (MarketConfig.timeZone, D-280) */
export const MARKET_TIME_ZONE: Readonly<Record<string, string>> = ${lit(pick((c) => c.timeZone))}

/** A mobile number written a market's own way: its pattern and the prefix for its leading zero (MarketConfig.phone) */
export const MARKET_PHONE: Readonly<Record<string, { mobile: string; prefix: string }>> = ${lit(pick((c) => c.phone))}
`
}

if (process.argv[1]?.endsWith('edge.ts')) {
  const text = edgeMarkets()
  if (process.argv.includes('--check')) {
    const current = readFileSync(EDGE_MARKETS_PATH, 'utf8')
    if (current !== text) {
      console.error(`${EDGE_MARKETS_PATH} is not current with lib/markets.ts: run npm run markets:edge`)
      process.exit(1)
    }
  } else writeFileSync(EDGE_MARKETS_PATH, text)
}
